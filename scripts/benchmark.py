#!/usr/bin/env python3
"""Benchmarks the engine against the pre-computed Stockfish library.

For every position in assets/stockfish_library.txt (generated by
scripts/generate_library.py), this runs the engine's own search (via the
`eval-fen` CLI subcommand) and compares its move and eval against
Stockfish's. Reports three accuracies - whether the engine found
Stockfish's exact best move, whether it found one of Stockfish's top 2, and
whether it found one of its top 5 - plus how close the evals are, then
saves a PNG summary of the run under benchmark_results/, including a
per-position table of id, game phase, and which of those tiers it hit.

Every position can be searched either to a fixed depth or for a fixed time,
asked for when the script starts. Fixed time is the honest way to compare
two versions of the engine: at a fixed depth a change that searches fewer
nodes per ply looks identical to one that searches them faster. Under a
time limit the depth reached becomes a result in its own right, so it is
reported per position and averaged.

Usage:
    scripts/.venv/bin/python3 scripts/benchmark.py

See scripts/requirements.txt for the one dependency (matplotlib); the venv
at scripts/.venv already has it installed.
"""

