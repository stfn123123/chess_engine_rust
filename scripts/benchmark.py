def ask_int(prompt, default):
    raw = input(f"{prompt} [{default}]: ").strip()
    return int(raw) if raw else default


def ask_str(prompt, default=None, required=False):
    while True:
        suffix = f" [{default}]" if default else ""
        raw = input(f"{prompt}{suffix}: ").strip()
        if raw:
            return raw
        if default is not None:
            return default
        if not required:
            return ""
        print("this value is required")


def parse_eval(text):
    if text.startswith("cp"):
        return ("cp", int(text[2:]))
    if text.startswith("mate"):
        return ("mate", int(text[4:]))
    raise ValueError(f"unrecognised eval {text!r}")


def eval_to_centipawns(parsed_eval):
    kind, value = parsed_eval
    if kind == "cp":
        return value
    return MATE_CENTIPAWN_CAP if value > 0 else -MATE_CENTIPAWN_CAP


def engine_score_to_centipawns(score):
    if abs(score) >= ENGINE_MATE_BOUND:
        return MATE_CENTIPAWN_CAP if score > 0 else -MATE_CENTIPAWN_CAP
    return score


def load_library(path):
    # one line per position: id \t fen \t phase \t move1 \t ... \t move5 \t eval -
    # the format scripts/generate_library.py writes and stockfish_library.rs reads
    positions = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        fields = line.split("\t")
        if len(fields) < 5:
            continue
        id_, fen, phase, *moves, eval_text = fields
        positions.append({
            "id": int(id_),
            "fen": fen,
            "phase": float(phase),
            "moves": moves,
            "eval": parse_eval(eval_text),
        })
    return positions


