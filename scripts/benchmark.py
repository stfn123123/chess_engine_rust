def run_engine(fen, depth, table_megabytes, time_ms):
    # time_ms of 0 means no time limit, in which case depth is what bounds the
    # search; with a time given, depth is only a ceiling
    result = subprocess.run(
        [str(BINARY), "eval-fen", fen, str(depth), str(table_megabytes), str(time_ms)],
        capture_output=True,
        text=True,
        timeout=time_ms / 1000 + TIMEOUT_SLACK_SECONDS,
    )
    line = result.stdout.strip()
    if not line:
        raise RuntimeError(f"no output (stderr: {result.stderr.strip()})")

    fields = dict(part.split("=", 1) for part in line.split() if "=" in part)
    if "error" in fields:
        raise RuntimeError(fields["error"])

    return {
        "bestmove": fields["bestmove"],
        "score": int(fields["score"]),
        "depth": int(fields["depth"]),
        "nodes": int(fields["nodes"]),
        "time_ms": int(fields["time_ms"]),
    }


def safe_filename(name):
    cleaned = "".join(char if char.isalnum() or char in "-_" else "_" for char in name.strip())
    return cleaned or "run"



# per-position status -> table cell colour in the detail grid the PNG ends with
STATUS_COLORS = {
    "BEST": "#6aa84f",
    "TOP2": "#93c47d",
    "TOP5": "#ffd966",
    "MISS": "#e06666",
}


def render_png(*, run_name, limit_label, avg_depth, depth_range, table_megabytes,
                library_path, total, evaluated, top5_accuracy, top2_accuracy,
                best_accuracy, avg_eval_diff, total_nodes, elapsed, nps,
                positions_detail):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    output_path = RESULTS_DIR / f"{safe_filename(run_name)}.png"

    # the per-position table below the summary card needs room proportional to
    # how many positions there are - the summary card itself is a fixed size
    n_groups = min(4, max(1, len(positions_detail)))
    rows_per_group = -(-len(positions_detail) // n_groups) if positions_detail else 0
    summary_height = 6.0
    table_height = 0.4 + rows_per_group * 0.22 if positions_detail else 0
    fig_height = summary_height + table_height

    fig = plt.figure(figsize=(12, fig_height))
    summary_fraction = summary_height / fig_height

    ax = fig.add_axes([0.05, 1 - summary_fraction + 0.02, 0.9, summary_fraction - 0.06])
    ax.axis("off")

    fig.suptitle(run_name, fontsize=20, fontweight="bold")
    ax.text(
        0.5, 1.0, datetime.now().strftime("%Y-%m-%d %H:%M"),
        ha="center", va="top", fontsize=10, color="gray", transform=ax.transAxes,
    )

    hyperparameters = (
        f"search limit: {limit_label}\n"
        f"table size: {table_megabytes} MB\n"
        f"positions file: {library_path.name}\n"
        f"positions evaluated: {evaluated}/{total}"
    )
    ax.text(0.05, 0.88, hyperparameters, fontsize=11, va="top", family="monospace",
            transform=ax.transAxes)

    low, high = depth_range
    stats = [
        ("Best-move accuracy", f"{best_accuracy:.1f}%"),
        ("Top-2 accuracy", f"{top2_accuracy:.1f}%"),
        ("Top-5 accuracy", f"{top5_accuracy:.1f}%"),
        ("Avg eval diff", f"{avg_eval_diff:.0f} cp"),
        ("Depth reached", f"{avg_depth:.1f} ({low}-{high})"),
        ("Nodes searched", f"{total_nodes:,}"),
        ("Total time", f"{elapsed:.1f} s"),
        ("Nodes/sec", f"{nps:,.0f}"),
    ]

    y = 0.62
    for label, value in stats:
        ax.text(0.05, y, label, fontsize=13, transform=ax.transAxes)
        ax.text(0.95, y, value, fontsize=13, ha="right", fontweight="bold", transform=ax.transAxes)
        y -= 0.075

    if positions_detail:
        ax_table = fig.add_axes([0.02, 0.02, 0.96, table_height / fig_height - 0.02])
        ax_table.axis("off")

        chunks = [
            positions_detail[i * rows_per_group:(i + 1) * rows_per_group]
            for i in range(n_groups)
        ]

        cell_text = []
        cell_colors = []
        for row in range(rows_per_group):
            row_text = []
            row_colors = []
            for chunk in chunks:
                if row < len(chunk):
                    entry = chunk[row]
                    row_text += [
                        str(entry["id"]),
                        f"{entry['phase']:.2f}",
                        str(entry["depth"]),
                        entry["status"],
                    ]
                    row_colors += ["white", "white", "white", STATUS_COLORS[entry["status"]]]
                else:
                    row_text += ["", "", "", ""]
                    row_colors += ["white", "white", "white", "white"]
            cell_text.append(row_text)
            cell_colors.append(row_colors)

        col_labels = ["ID", "Phase", "Depth", "Result"] * n_groups
        table = ax_table.table(
            cellText=cell_text,
            colLabels=col_labels,
            cellColours=cell_colors,
            colColours=["#dddddd"] * len(col_labels),
            loc="center",
            cellLoc="center",
        )
        table.auto_set_font_size(False)
        table.set_fontsize(8)
        table.scale(1, 1.3)

    fig.savefig(output_path, dpi=150)
    plt.close(fig)
    return output_path


def main():
    print("=== Engine vs. Stockfish benchmark ===\n")

    # a fixed depth measures what the engine finds; a fixed time measures what it
    # finds for the money, which is what comparing two versions wants
    mode = ask_str("Limit by (d)epth or (t)ime", default="d").lower()
    if mode.startswith("t"):
        seconds = ask_int("Seconds per position", 30)
        time_ms = seconds * 1000
        depth = MAX_SEARCH_DEPTH
        limit_label = f"{seconds} s / position"
    else:
        time_ms = 0
        depth = ask_int("Search depth", 6)
        limit_label = f"depth {depth}"

    run_name = ask_str("Run name", required=True)
    library_path = Path(ask_str("Positions library file", default=str(DEFAULT_LIBRARY)))
    table_megabytes = ask_int("Transposition table size (MB)", 64)

    if not library_path.exists():
        print(f"\n{library_path} does not exist - generate it first with:")
        print(f"  cargo run --release -- generate-library <positions.txt>")
        sys.exit(1)

    positions = load_library(library_path)
    if not positions:
        print(f"\nno positions found in {library_path}")
        sys.exit(1)

    # menu = "\n".join(f"  {key}) {label}" for key, label in FILTER_CHOICES.items())
    # print(f"\nWhich positions to run?\n{menu}")
    # filter_choice = ask_str("Choice", default=FILTER_ALL)
    # positions = filter_positions(positions, filter_choice)
    # if not positions:
    #     print(f"\nno positions match filter {FILTER_CHOICES[filter_choice]!r}")
    #     sys.exit(1)

    print("\nbuilding release binary...")
    try:
        subprocess.run(["cargo", "build", "--release"], cwd=REPO_ROOT, check=True)
    except subprocess.CalledProcessError:
        print("cargo build failed - fix the build before benchmarking")
        sys.exit(1)

    total = len(positions)
    best_hits = 0
    top2_hits = 0
    top5_hits = 0
    eval_diffs = []
    depths = []
    total_nodes = 0
    positions_detail = []

    print(f"\nevaluating {total} positions at {limit_label}...")
    if time_ms:
        # the whole run is priced up front under a time limit, unlike a depth
        print(f"that is about {total * time_ms / 1000 / 60:.0f} minutes\n")
    else:
        print()
    started = time.time()

    for index, position in enumerate(positions, start=1):
        print(f"[{index}/{total}] evaluating...", end=" ", flush=True)

        try:
            result = run_engine(position["fen"], depth, table_megabytes, time_ms)
        except Exception as error:
            print(f"ERROR: {error}")
            continue

        engine_move = result["bestmove"]
        stockfish_moves = position["moves"]
        best_move = stockfish_moves[0] if stockfish_moves else None

        is_best = engine_move == best_move
        is_top2 = engine_move in stockfish_moves[:2]
        is_top5 = engine_move in stockfish_moves
        best_hits += is_best
        top2_hits += is_top2
        top5_hits += is_top5

        diff = abs(
            engine_score_to_centipawns(result["score"]) - eval_to_centipawns(position["eval"])
        )
        eval_diffs.append(diff)
        depths.append(result["depth"])
        total_nodes += result["nodes"]

        status = "BEST" if is_best else ("TOP2" if is_top2 else ("TOP5" if is_top5 else "MISS"))
        positions_detail.append({
            "id": position["id"],
            "status": status,
            "phase": position["phase"],
            "depth": result["depth"],
        })
        print(
            f"{engine_move:>6} vs {best_move or '?':>6} [{status:>4}]"
            f" d{result['depth']:<2} eval diff {diff:5d}cp"
        )

    elapsed = time.time() - started
    evaluated = len(eval_diffs)

    if evaluated == 0:
        print("\nno position was evaluated successfully")
        sys.exit(1)

    top5_accuracy = 100 * top5_hits / evaluated
    top2_accuracy = 100 * top2_hits / evaluated
    best_accuracy = 100 * best_hits / evaluated
    avg_eval_diff = statistics.mean(eval_diffs)
    avg_depth = statistics.mean(depths)
    nps = total_nodes / elapsed if elapsed > 0 else 0

    print("\n=== Results ===")
    print(f"positions evaluated:  {evaluated}/{total}")
    print(f"best-move accuracy:   {best_accuracy:.1f}%")
    print(f"top-2 accuracy:       {top2_accuracy:.1f}%")
    print(f"top-5 accuracy:       {top5_accuracy:.1f}%")
    print(f"avg eval diff:        {avg_eval_diff:.0f} cp")
    print(f"depth reached:        {avg_depth:.1f} avg ({min(depths)}-{max(depths)})")
    print(f"nodes searched:       {total_nodes:,}")
    print(f"total time:           {elapsed:.1f} s")
    print(f"nodes/sec:            {nps:,.0f}")

    output_path = render_png(
        run_name=run_name,
        limit_label=limit_label,
        avg_depth=avg_depth,
        depth_range=(min(depths), max(depths)),
        table_megabytes=table_megabytes,
        library_path=library_path,
        total=total,
        evaluated=evaluated,
        top5_accuracy=top5_accuracy,
        top2_accuracy=top2_accuracy,
        best_accuracy=best_accuracy,
        avg_eval_diff=avg_eval_diff,
        total_nodes=total_nodes,
        elapsed=elapsed,
        nps=nps,
        positions_detail=positions_detail,
    )
    print(f"\nsaved {output_path}")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\ninterrupted")
        sys.exit(1)
